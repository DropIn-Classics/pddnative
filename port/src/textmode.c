static uint8_t font[256][16];           /* bit 7 the left pixel */
static int font_made;

/* lines: single ones 2 pixels wide (columns 3-4) and 1 high (row 8),
 * double ones at columns 1-2 and 5-6, rows 6 and 10 */
static void hline(uint8_t *g, int y, int x0, int x1)
{
    int x;
    for (x = x0; x <= x1; x++)
        g[y] |= (uint8_t)(0x80 >> x);
}

static void vline(uint8_t *g, int x, int y0, int y1)
{
    int y;
    for (y = y0; y <= y1; y++)
        g[y] |= (uint8_t)(0xC0 >> x);   /* columns x and x + 1 */
}

static void make_lines(void)
{
    uint8_t *g;

    g = font[TM_H];              hline(g, 8, 0, 7);
    g = font[TM_V];              vline(g, 3, 0, 15);
    g = font[TM_HH];             hline(g, 6, 0, 7); hline(g, 10, 0, 7);
    g = font[TM_VV];             vline(g, 1, 0, 15); vline(g, 5, 0, 15);
    g = font[TM_TOP_LEFT];       hline(g, 8, 3, 7); vline(g, 3, 8, 15);
    g = font[TM_TOP_RIGHT];      hline(g, 8, 0, 4); vline(g, 3, 8, 15);
    g = font[TM_BOTTOM_LEFT];    hline(g, 8, 3, 7); vline(g, 3, 0, 8);
    g = font[TM_BOTTOM_RIGHT];   hline(g, 8, 0, 4); vline(g, 3, 0, 8);
    g = font[TM_V_RIGHT];        vline(g, 3, 0, 15); hline(g, 8, 3, 7);
    g = font[TM_V_LEFT];         vline(g, 3, 0, 15); hline(g, 8, 0, 4);
    g = font[TM_VV_RIGHT];       vline(g, 1, 0, 15); vline(g, 5, 0, 15); hline(g, 8, 5, 7);
    g = font[TM_VV_LEFT];        vline(g, 1, 0, 15); vline(g, 5, 0, 15); hline(g, 8, 0, 2);
    /* the double corners: an outer and an inner line */
    g = font[TM_DD_TOP_LEFT];    hline(g, 6, 1, 7); vline(g, 1, 6, 15); hline(g, 10, 5, 7); vline(g, 5, 10, 15);
    g = font[TM_DD_TOP_RIGHT];   hline(g, 6, 0, 6); vline(g, 5, 6, 15); hline(g, 10, 0, 2); vline(g, 1, 10, 15);
    g = font[TM_DD_BOTTOM_LEFT]; hline(g, 10, 1, 7); vline(g, 1, 0, 10); hline(g, 6, 5, 7); vline(g, 5, 0, 6);
    g = font[TM_DD_BOTTOM_RIGHT]; hline(g, 10, 0, 6); vline(g, 5, 0, 10); hline(g, 6, 0, 2); vline(g, 1, 0, 6);
    g = font[TM_VV_RIGHT2];      vline(g, 1, 0, 15); vline(g, 5, 0, 6); hline(g, 6, 5, 7);
                                 vline(g, 5, 10, 15); hline(g, 10, 5, 7);
    g = font[TM_VV_LEFT2];       vline(g, 5, 0, 15); vline(g, 1, 0, 6); hline(g, 6, 0, 2);
                                 vline(g, 1, 10, 15); hline(g, 10, 0, 2);
}

static void make_shapes(void)
{
    int y, k;

    for (y = 0; y < 16; y++) {
        font[TM_SHADE_LIGHT][y] = (uint8_t)(y & 1 ? 0x22 : 0x88);
        font[TM_SHADE_MEDIUM][y] = (uint8_t)(y & 1 ? 0x55 : 0xAA);
        font[TM_SHADE_DARK][y] = (uint8_t)(y & 1 ? 0xDD : 0x77);
        font[TM_BLOCK][y] = 0xFF;
        font[TM_LOWER_HALF][y] = (uint8_t)(y >= 8 ? 0xFF : 0);
        font[TM_UPPER_HALF][y] = (uint8_t)(y < 8 ? 0xFF : 0);
    }
    font[TM_MIDDLE_DOT][7] = font[TM_MIDDLE_DOT][8] = 0x18;
    for (y = 5; y <= 10; y++)
        font[TM_SQUARE][y] = 0x7E;
    for (k = 0; k < 4; k++) {
        uint8_t row = (uint8_t)((0xFF >> (3 - k)) & (0xFF << (3 - k)));   /* 2k + 2 wide, centred */
        font[TM_UP_TRIANGLE][6 + k] = font[TM_DOWN_TRIANGLE][9 - k] = row;
        font[TM_UP_ARROW][2 + k] = font[TM_DOWN_ARROW][13 - k] = row;
    }
    for (y = 6; y <= 13; y++)
        font[TM_UP_ARROW][y] |= 0x18;
    for (y = 2; y <= 9; y++)
        font[TM_DOWN_ARROW][y] |= 0x18;
    /* the pointing triangles: 7 columns, 1 to 13 rows high */
    for (k = 0; k < 7; k++)
        for (y = 8 - (6 - k); y <= 8 + (6 - k); y++) {
            font[TM_RIGHT_TRIANGLE][y] |= (uint8_t)(0x80 >> k);
            font[TM_LEFT_TRIANGLE][y] |= (uint8_t)(0x02 << k);
        }
    /* the horizontal arrows: a shaft on rows 7-8, a head of 4 columns */
    for (k = 0; k < 4; k++)
        for (y = 4 + k; y <= 11 - k; y++) {
            font[TM_RIGHT_ARROW][y] |= (uint8_t)(0x08 >> k);
            font[TM_LEFT_ARROW][y] |= (uint8_t)(0x10 << k);
        }
    font[TM_RIGHT_ARROW][7] |= 0xF8;
    font[TM_RIGHT_ARROW][8] |= 0xF8;
    font[TM_LEFT_ARROW][7] |= 0x1F;
    font[TM_LEFT_ARROW][8] |= 0x1F;
}

static void make_font(void)
{
    int band, row, g, c;

    for (band = 0; band < 12; band++)
        for (row = 0; row < 13; row++)
            for (g = 0; g < 8; g++) {
                const char *s = art[band * 13 + row] + 9 * g;
                for (c = 0; c < 8; c++)
                    if (s[c] == '#')
                        font[0x20 + 8 * band + g][2 + row] |= (uint8_t)(0x80 >> c);
            }
    make_lines();
    make_shapes();
    font_made = 1;
}

/* ---- the screen */

void tm_clear(uint8_t ch, uint8_t attr)
{
    memset(chars, ch, sizeof chars);
    memset(attrs, attr, sizeof attrs);
}

void tm_put(int x, int y, uint8_t ch, uint8_t attr)
{
    if (x >= 0 && x < TM_COLS && y >= 0 && y < TM_ROWS) {
        chars[y][x] = ch;
        attrs[y][x] = attr;
    }
}

int tm_text(int x, int y, const char *s, uint8_t attr)
{
    for (; *s; s++, x++)
        tm_put(x, y, (uint8_t)*s, attr);
    return x;
}

void tm_fill(int x, int y, int w, int h, uint8_t ch, uint8_t attr)
{
    int i, j;
    for (j = y; j < y + h; j++)
        for (i = x; i < x + w; i++)
            tm_put(i, j, ch, attr);
}

void tm_frame(int x, int y, int w, int h, uint8_t attr)
{
    int i;

    for (i = x + 1; i < x + w - 1; i++) {
        tm_put(i, y, TM_HH, attr);
        tm_put(i, y + h - 1, TM_HH, attr);
    }
    for (i = y + 1; i < y + h - 1; i++) {
        tm_put(x, i, TM_VV, attr);
        tm_put(x + w - 1, i, TM_VV, attr);
    }
    tm_put(x, y, TM_DD_TOP_LEFT, attr);
    tm_put(x + w - 1, y, TM_DD_TOP_RIGHT, attr);
    tm_put(x, y + h - 1, TM_DD_BOTTOM_LEFT, attr);
    tm_put(x + w - 1, y + h - 1, TM_DD_BOTTOM_RIGHT, attr);
}

static void shade(int x, int y)
{
    if (x >= 0 && x < TM_COLS && y >= 0 && y < TM_ROWS)
        attrs[y][x] = TM_ATTR(TM_DARKGREY, TM_BLACK);
}

void tm_shadow(int x, int y, int w, int h)
{
    int i;
    for (i = y + 1; i <= y + h; i++) {
        shade(x + w, i);
        shade(x + w + 1, i);
    }
    for (i = x + 2; i < x + w; i++)
        shade(i, y + h);
}

/* the CGA colours as a VGA's text mode sets them (6-bit DAC values 0, 2Ah,
 * 15h, 3Fh; brown with half green) */
static const uint32_t cga[16] = {
    0x000000, 0x0000AA, 0x00AA00, 0x00AAAA, 0xAA0000, 0xAA00AA, 0xAA5500, 0xAAAAAA,
    0x555555, 0x5555FF, 0x55FF55, 0x55FFFF, 0xFF5555, 0xFF55FF, 0xFFFF55, 0xFFFFFF
};

void tm_render(uint8_t *pixels, uint32_t palette[256])
{
    int x, y, r, b;

    if (!font_made)
        make_font();
    for (b = 0; b < 256; b++)
        palette[b] = cga[b & 15];
    for (y = 0; y < TM_ROWS; y++)
        for (x = 0; x < TM_COLS; x++) {
            const uint8_t *g = font[chars[y][x]];
            uint8_t fg = attrs[y][x] & 15, bg = attrs[y][x] >> 4;
            for (r = 0; r < 16; r++) {
                uint8_t *p = pixels + (y * 16 + r) * TM_WIDTH + x * 8;
                for (b = 0; b < 8; b++)
                    p[b] = g[r] & (0x80 >> b) ? fg : bg;
            }
        }
}
